"""AI Editing and Motion Graphics Copilot Agent for Luna-Cut.

Interprets natural language editing instructions, plans multi-layer motion graphics,
generates Bezier keyframe curves, 3D camera trajectories, and AI rotoscoping sandwiches,
and dispatches them as atomic batch edits.
"""

from dataclasses import dataclass, field
import json
import os
import re
from typing import Any, Dict, List, Optional

from .motion_graphics_generator import (
    BezierCurve,
    Camera3DChoreographer,
    KineticTypographyEngine,
    RotoSandwichBuilder,
)
from .timeline_client import ConcatTimelineClient


@dataclass
class EditPlan:
    """Structured plan generated by the AI Copilot."""
    summary: str
    actions: List[Dict[str, Any]]
    batch_command: Dict[str, Any]
    timeline_duration_delta: float = 0.0


class AICopilotAgent:
    """Orchestrates natural language editing and motion graphics generation."""

    def __init__(self, api_key: Optional[str] = None):
        self.api_key = api_key or os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
        self.client = ConcatTimelineClient()

    def plan_edit(self, prompt: str, timeline_context: Optional[Dict[str, Any]] = None) -> EditPlan:
        """Analyzes prompt and generates an atomic execution plan."""
        prompt_lower = prompt.lower()
        context = timeline_context or {
            "current_time_s": 0.0,
            "duration_s": 10.0,
            "tracks": [{"id": "track_0", "name": "Main Video"}],
            "clips": [{"id": "clip_0", "track_id": "track_0", "start": 0.0, "duration": 8.0, "media_id": "m0"}],
        }

        # 1. Check for AI Rotoscoping / Subject Cutout Sandwich
        if any(w in prompt_lower for w in ["roto", "cutout", "behind person", "behind subject", "magic touch"]):
            return self._plan_roto_sandwich(prompt, context)

        # 2. Check for 3D Camera Movement
        if any(w in prompt_lower for w in ["3d camera", "dolly", "orbit", "vertigo", "whip pan"]):
            return self._plan_3d_camera_choreography(prompt, context)

        # 3. Check for Kinetic Typography
        if any(w in prompt_lower for w in ["title", "text", "typography", "kinetic", "lyrics", "words"]):
            return self._plan_kinetic_typography(prompt, context)

        # Default: Hybrid cinematic motion graphics composition
        return self._plan_hybrid_cinematic(prompt, context)

    def _plan_kinetic_typography(self, prompt: str, context: Dict[str, Any]) -> EditPlan:
        """Generates kinetic typography layers with staggered Bezier keyframing."""
        # Extract title text in quotes if present, else default
        text_match = re.search(r'["\']([^"\']+)["\']', prompt)
        text = text_match.group(1) if text_match else "LUNA CUT MOTION"

        playhead = context.get("current_time_s", 0.0)
        staggered_clips = KineticTypographyEngine.generate_staggered_title(
            text=text,
            start_time=playhead,
            word_duration=2.5,
            stagger_delay=0.12,
            style="elastic_bounce",
            font_size=72.0,
            text_color="#FFDD33",
        )

        track_cmd = self.client.create_add_track_command("Kinetic Titles")
        batch_cmds: List[Dict[str, Any]] = [track_cmd]

        actions_summary = []
        for c in staggered_clips:
            # Add text clip
            text_cmd = self.client.create_text_clip_command(
                track_id="track_kinetic",
                start_s=c["start"],
                duration_s=c["duration"],
                text=c["text"],
                font_size=c["font_size"],
                color=c["color"],
            )
            # Add elastic bounce keyframes
            key_in = self.client.create_set_keyframe_command(
                clip_id=f"clip_text_{c['word_index']}",
                property_name="scale",
                time_s=c["start"],
                value=c["animation"]["initial_scale"],
                curve=c["animation"]["curve"],
            )
            key_out = self.client.create_set_keyframe_command(
                clip_id=f"clip_text_{c['word_index']}",
                property_name="scale",
                time_s=c["start"] + 0.35,
                value=c["animation"]["target_scale"],
                curve=c["animation"]["curve"],
            )
            batch_cmds.extend([text_cmd, key_in, key_out])
            actions_summary.append(f"Add kinetic word '{c['text']}' at {c['start']}s with elastic bounce")

        summary = f"Generated kinetic typography for '{text}' ({len(staggered_clips)} words) with elastic Bezier easing."
        batch = self.client.build_batch_command(batch_cmds)
        return EditPlan(summary=summary, actions=batch_cmds, batch_command=batch)

    def _plan_3d_camera_choreography(self, prompt: str, context: Dict[str, Any]) -> EditPlan:
        """Generates 3D camera motion (Dolly Zoom / Orbit / Whip Pan)."""
        playhead = context.get("current_time_s", 0.0)
        prompt_lower = prompt.lower()

        batch_cmds: List[Dict[str, Any]] = []
        if "orbit" in prompt_lower:
            trajectory = Camera3DChoreographer.orbit_360(start_time=playhead, duration=4.0, radius=900.0)
            summary = f"Configured 360-degree 3D Camera Orbit trajectory ({len(trajectory)} motion samples)."
            for pt in trajectory[::3]:  # sample keyframes
                batch_cmds.append(
                    self.client.create_set_keyframe_command(
                        clip_id="camera_3d",
                        property_name="rotation_y",
                        time_s=pt["time"],
                        value=pt["rotation_y"],
                    )
                )
        elif "whip" in prompt_lower:
            whip = Camera3DChoreographer.whip_pan(start_time=playhead, duration=0.35, direction="right")
            summary = "Applied high-velocity 3D Whip Pan transition with motion blur curve."
            batch_cmds.append(
                self.client.create_set_keyframe_command(
                    clip_id="camera_3d",
                    property_name="rotation_y",
                    time_s=playhead + whip["duration"],
                    value=whip["rotation_y_delta"],
                    curve=whip["curve"],
                )
            )
        else:
            # Default to Dolly Zoom (Vertigo)
            dolly_steps = Camera3DChoreographer.dolly_zoom(start_time=playhead, duration=3.0)
            summary = f"Choreographed 3D Dolly Zoom (Vertigo effect) adjusting camera distance and FOV."
            for pt in dolly_steps[::4]:
                batch_cmds.append(
                    self.client.create_set_keyframe_command(
                        clip_id="camera_3d",
                        property_name="position_z",
                        time_s=pt["time"],
                        value=pt["camera_z"],
                    )
                )
                batch_cmds.append(
                    self.client.create_set_keyframe_command(
                        clip_id="camera_3d",
                        property_name="fov",
                        time_s=pt["time"],
                        value=pt["camera_fov"],
                    )
                )

        batch = self.client.build_batch_command(batch_cmds)
        return EditPlan(summary=summary, actions=batch_cmds, batch_command=batch)

    def _plan_roto_sandwich(self, prompt: str, context: Dict[str, Any]) -> EditPlan:
        """Builds a 3-layer depth sandwich: Background Video -> Text -> Cutout Foreground."""
        text_match = re.search(r'["\']([^"\']+)["\']', prompt)
        text = text_match.group(1) if text_match else "CYBERPUNK"

        clips = context.get("clips", [])
        base_clip = clips[0] if clips else {"id": "c0", "media_id": "m0", "duration": 6.0}

        spec = RotoSandwichBuilder.build_sandwich_spec(
            video_clip_id=base_clip["id"],
            media_id=base_clip.get("media_id", "m0"),
            start_time=0.0,
            duration=base_clip.get("duration", 6.0),
            text=text,
            stroke_color="#00FFAA",
            stroke_width=5.0,
        )

        batch_cmds = [
            self.client.create_add_track_command("Text Layer (Mid Depth)"),
            self.client.create_add_track_command("Subject Cutout (Foreground)"),
            self.client.create_text_clip_command(
                track_id="track_1",
                start_s=spec["kinetic_text"]["start"],
                duration_s=spec["kinetic_text"]["duration"],
                text=spec["kinetic_text"]["text"],
                font_size=84.0,
                color="#FFFFFF",
            ),
            self.client.create_cutout_command(clip_id="clip_fg_cutout", enabled=True),
            self.client.create_cutout_stroke_command(
                clip_id="clip_fg_cutout",
                color=spec["cutout_foreground"]["stroke"]["color"],
                width=spec["cutout_foreground"]["stroke"]["width"],
            ),
        ]

        summary = f"Assembled 3D Depth Sandwich: Rotoscope subject with '{text}' nestled in 3D depth behind foreground."
        batch = self.client.build_batch_command(batch_cmds)
        return EditPlan(summary=summary, actions=batch_cmds, batch_command=batch)

    def _plan_hybrid_cinematic(self, prompt: str, context: Dict[str, Any]) -> EditPlan:
        """Combines kinetic typography, 3D camera pan, and glow effect."""
        text_plan = self._plan_kinetic_typography(prompt, context)
        camera_plan = self._plan_3d_camera_choreography(prompt, context)

        combined_actions = text_plan.actions + camera_plan.actions
        batch = self.client.build_batch_command(combined_actions)
        summary = f"Composed full cinematic motion graphics: {text_plan.summary} + {camera_plan.summary}"
        return EditPlan(summary=summary, actions=combined_actions, batch_command=batch)
